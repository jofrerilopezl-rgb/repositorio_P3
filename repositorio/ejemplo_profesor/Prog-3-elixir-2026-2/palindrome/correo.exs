1. la universidad desea crear un aplicaicon que generar
el correo institucional de los estudiantes
 a partir de su nombre y apellido.
 El formato del correo será: primer nombre + .+ primer apellido + @uniquindio.edu.con
 Por ejemplo, si el estudiante se llama Juan Pérez, su correo institucional
 se generará como  juan.perez@uniquindio.edu.co

2. Una red social desea validar de forma sencilla los nombres de usuario que eligen las personas al registrarse. Por ahora, la única regla es que el nombre de usuario debe tener al menos 5 caracteres (sin contar los espacios al inicio o al final).

El programa debe:

Solicitar al usuario el nombre de usuario que desea registrar.
Eliminar los espacios en blanco al inicio y al final.
Calcular su longitud usando la función String.length/1.
Mostrar un mensaje según el resultado:
Si tiene 5 caracteres o más: "Nombre de usuario válido".
Si tiene menos de 5 caracteres: "Nombre de usuario muy corto, debe tener al menos 5 caracteres".
Tenga en cuenta lo siguiente:

Use la estructura if/else para decidir el mensaje a mostrar.
Separe la lógica en funciones pequeñas y documente el módulo

